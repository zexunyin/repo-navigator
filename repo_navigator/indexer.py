"""Persistent structural indexes and agent-maintained semantic descriptions."""

from __future__ import annotations

import json
import os
from collections import Counter
from pathlib import Path
from typing import Any

from .scanner import collect_structure

INDEX_DIRECTORY = ".ai"


def read_json(path: Path, default: dict[str, Any] | None = None) -> dict[str, Any]:
    if not path.exists():
        if default is not None:
            return default
        raise ValueError(f"Missing index: {path}")
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict) or value.get("schema_version") != 1:
        raise ValueError(f"Unsupported or invalid index schema: {path}")
    return value


def write_text_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    temporary_path = path.with_name(path.name + ".tmp")
    temporary_path.write_text(content, encoding="utf-8", newline="\n")
    os.replace(temporary_path, path)


def write_json(path: Path, data: dict[str, Any]) -> None:
    write_text_if_changed(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")


def semantic_status(symbol: dict[str, Any], definition: dict[str, Any] | None) -> str:
    if not isinstance(definition, dict) or not str(definition.get("purpose", "")).strip() \
            or not str(definition.get("owner", "")).strip() \
            or not definition.get("reviewed_hash"):
        return "missing"
    if definition["reviewed_hash"] != symbol["source_hash"]:
        return "stale"
    return "verified"


def make_semantics(symbols: list[dict[str, Any]], existing: dict[str, Any]) -> dict[str, Any]:
    prior_entries = existing.get("entries", {})
    if not isinstance(prior_entries, dict):
        raise ValueError("Invalid semantics.json: entries must be an object")
    entries: dict[str, Any] = {}
    for symbol in symbols:
        entries[symbol["id"]] = prior_entries.get(symbol["id"], {
            "purpose": "", "owner": "", "side_effects": [], "reviewed_hash": None,
        })
    return {"schema_version": 1, "entries": entries}


def escape_cell(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def generate_markdown(files: dict[str, Any], symbols: dict[str, Any], semantics: dict[str, Any]) -> str:
    definitions = semantics["entries"]
    by_file: dict[str, list[dict[str, Any]]] = {}
    for symbol in symbols["symbols"]:
        by_file.setdefault(symbol["file"], []).append(symbol)
    lines = [
        "# Repository Navigation Index", "",
        "> Generated by `repo-nav scan`. Do not hand-edit this file; edit `.ai/semantics.json`.",
        "> Source code is authoritative. Verify definitions before making changes.", "",
        "## Files", "", "| File | Language | Symbols | Needs review |",
        "| --- | --- | ---: | ---: |",
    ]
    for file in files["files"]:
        related = by_file.get(file["path"], [])
        pending = sum(semantic_status(sym, definitions.get(sym["id"])) != "verified" for sym in related)
        lines.append(
            f"| `{escape_cell(file['path'])}` | {file['language']} | {len(related)} | {pending} |"
        )
    lines.extend(["", "## Symbols by file", ""])
    for file in files["files"]:
        related = by_file.get(file["path"], [])
        if not related:
            continue
        lines.extend([
            f"### `{escape_cell(file['path'])}`", "",
            "| Symbol | Lines | Purpose | Review |", "| --- | ---: | --- | --- |",
        ])
        for symbol in related:
            definition = definitions.get(symbol["id"], {})
            status = semantic_status(symbol, definition)
            lines.append(
                f"| `{escape_cell(symbol['qualified_name'])}` | "
                f"{symbol['start_line']}-{symbol['end_line']} | "
                f"{escape_cell(definition.get('purpose', ''))} | {status} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def scan(root: Path) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    files, symbols = collect_structure(root)
    index_dir = root / INDEX_DIRECTORY
    previous = read_json(index_dir / "semantics.json", {"schema_version": 1, "entries": {}})
    semantics = make_semantics(symbols["symbols"], previous)
    markdown = generate_markdown(files, symbols, semantics)
    write_json(index_dir / "files.json", files)
    write_json(index_dir / "symbols.json", symbols)
    write_json(index_dir / "semantics.json", semantics)
    write_text_if_changed(index_dir / "INDEX.md", markdown)
    return files, symbols, semantics


def inspect(root: Path) -> tuple[list[str], Counter[str], list[dict[str, Any]]]:
    """Check current source without modifying indexes or agent-authored definitions."""
    index_dir = root / INDEX_DIRECTORY
    files, symbols = collect_structure(root)
    problems: list[str] = []
    try:
        stored_files = read_json(index_dir / "files.json")
        stored_symbols = read_json(index_dir / "symbols.json")
        stored_semantics = read_json(index_dir / "semantics.json")
        if files != stored_files or symbols != stored_symbols:
            problems.append("Source index is outdated. Run: repo-nav scan .")
        if generate_markdown(stored_files, stored_symbols, stored_semantics) != (
            (index_dir / "INDEX.md").read_text(encoding="utf-8")
            if (index_dir / "INDEX.md").exists() else None
        ):
            problems.append("Navigation Markdown is outdated. Run: repo-nav scan .")
    except (ValueError, OSError, json.JSONDecodeError) as error:
        problems.append(str(error))
        stored_semantics = {"entries": {}}
    entries = stored_semantics.get("entries", {})
    counts: Counter[str] = Counter()
    pending: list[dict[str, Any]] = []
    for symbol in symbols["symbols"]:
        state = semantic_status(symbol, entries.get(symbol["id"]))
        counts[state] += 1
        if state != "verified":
            pending.append({**symbol, "status": state})
    if set(entries) != {symbol["id"] for symbol in symbols["symbols"]}:
        problems.append("Semantic entries do not match current symbols. Run: repo-nav scan .")
    return problems, counts, pending
